  function getDateKey(date = new Date()) {
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, '0');
    const day = String(date.getDate()).padStart(2, '0');
    return `${year}-${month}-${day}`;
  }

  function getDateLabel(date = new Date()) {
    const month = date.getMonth() + 1;
    const day = date.getDate();
    return `${month} 月 ${day} 日`;
  }

  function hashSeed(seed) {
    let hash = 0;
    for (let i = 0; i < seed.length; i++) {
      hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
    }
    return hash;
  }

  function get(direction = 'general', date = new Date()) {
    const key = wisdomByDirection[direction] ? direction : 'general';
    const list = wisdomByDirection[key];
    const seed = `${getDateKey(date)}:${key}`;
    const index = hashSeed(seed) % list.length;
    return {
      direction: key,
      dateKey: getDateKey(date),
      dateLabel: getDateLabel(date),
      text: list[index]
    };
  }

